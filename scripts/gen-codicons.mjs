#!/usr/bin/env node
// The chrome's icons are VS Code's own codicons, shipped as PATH DATA rather
// than the icon font: the tree draws them inside its own `<svg>`, and the
// static viewer has no font to load. This script reads each icon in NAMES from
// the pinned `@vscode/codicons` devDependency and writes web/src/codicon.ts —
// a `{name: {size, paths}}` table every `Codicon` is drawn from. Every
// `<path>` is kept, with its `fill-rule`; a `<rect>` becomes the path it draws.
//
//     node scripts/gen-codicons.mjs            rewrite web/src/codicon.ts
//     node scripts/gen-codicons.mjs --check    exit 1 if it is out of date
//
// To add an icon: add its name below (the file name in
// node_modules/@vscode/codicons/src/icons/), run the script, commit both.
// The icons are CC-BY-4.0 (Microsoft); NOTICE carries the attribution.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");
const pkgDir = join(root, "web/node_modules/@vscode/codicons");
const out = join(root, "web/src/codicon.ts");

/** Every icon the chrome draws, in groups by where it is used. */
const NAMES = [
  // status bar: the settings' glyph forms, pagers, `?`, Marks
  "list-tree", "layout-sidebar-left", "layout", "split-horizontal", "type-hierarchy-super",
  "window", "word-wrap", "comment", "eye-closed", "comment-discussion", "sparkle",
  "eye", "chevron-left", "chevron-right", "chevron-down", "chevron-up",
  "question", "bookmark", "check", "blank",
  // problems: the count item, the message strip, a node's popover
  "error", "warning", "info", "arrow-up", "arrow-down", "close",
  // the zoom rail
  "zoom-in", "zoom-out", "screen-full", "expand-all", "collapse-all",
  // the hover bar and the `⋯` menu
  "go-to-file", "target", "debug-step-over", "filter", "trash", "references",
  "wand", "fold-down", "fold-up", "lightbulb-autofix", "add", "remove",
  "ellipsis", "edit", "pin", "pinned", "loading",
];

const version = JSON.parse(readFileSync(join(pkgDir, "package.json"), "utf8")).version;

const attrs = (s) =>
  Object.fromEntries([...s.matchAll(/([a-zA-Z:-]+)="([^"]*)"/g)].map((m) => [m[1], m[2]]));

function parse(name) {
  const src = readFileSync(join(pkgDir, "src/icons", `${name}.svg`), "utf8");
  const svg = /<svg\b([^>]*)>/.exec(src);
  if (!svg) throw new Error(`${name}: no <svg>`);
  const vb = (attrs(svg[1]).viewBox ?? "").split(/\s+/).map(Number);
  if (vb.length !== 4 || vb[0] !== 0 || vb[1] !== 0 || vb[2] !== vb[3])
    throw new Error(`${name}: unexpected viewBox ${attrs(svg[1]).viewBox}`);
  const paths = [];
  for (const m of src.matchAll(/<(\w+)\b([^>]*?)\/?>/g)) {
    const [, tag, rest] = m;
    if (tag === "svg") continue;
    const a = attrs(rest);
    for (const k of Object.keys(a))
      if (!["d", "fill-rule", "clip-rule", "x", "y", "width", "height"].includes(k))
        throw new Error(`${name}: <${tag}> carries ${k}, which this table does not keep`);
    if (tag === "path") {
      paths.push({ d: a.d, evenodd: a["fill-rule"] === "evenodd" });
    } else if (tag === "rect") {
      const [x, y, w, h] = [a.x ?? 0, a.y ?? 0, a.width, a.height].map(Number);
      paths.push({ d: `M${x} ${y}h${w}v${h}h${-w}z`, evenodd: false });
    } else {
      throw new Error(`${name}: <${tag}> is not handled`);
    }
  }
  return { size: vb[2], paths };
}

const rows = NAMES.map((n) => {
  const { size, paths } = parse(n);
  const ps = paths
    .map((p) => (p.evenodd ? `{ d: ${JSON.stringify(p.d)}, evenodd: true }` : `{ d: ${JSON.stringify(p.d)} }`))
    .join(", ");
  return `  ${JSON.stringify(n)}: { size: ${size}, paths: [${ps}] },`;
});

const text = `// GENERATED by scripts/gen-codicons.mjs from @vscode/codicons ${version} — do not edit by hand.
// The codicons are © Microsoft Corporation, CC-BY-4.0 (see NOTICE). Drawn by \`Codicon\` (codiconView.tsx).

/** One codicon as path data: its square viewBox side and every path it draws
 (an \`evenodd\` path keeps its fill rule). */
export interface CodiconData {
  size: number;
  paths: readonly { d: string; evenodd?: true }[];
}

export const CODICONS = {
${rows.join("\n")}
} as const satisfies Record<string, CodiconData>;

export type CodiconName = keyof typeof CODICONS;
`;

const cur = (() => {
  try {
    return readFileSync(out, "utf8");
  } catch {
    return "";
  }
})();
if (check) {
  if (cur !== text) {
    console.error("web/src/codicon.ts is out of date — run node scripts/gen-codicons.mjs");
    process.exit(1);
  }
  console.log(`codicon.ts is current (${NAMES.length} icons, @vscode/codicons ${version})`);
} else {
  if (cur !== text) writeFileSync(out, text);
  console.log(`${cur === text ? "unchanged" : "wrote"} web/src/codicon.ts (${NAMES.length} icons, @vscode/codicons ${version})`);
}
