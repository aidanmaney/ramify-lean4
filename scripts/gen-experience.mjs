#!/usr/bin/env node
// One source for what each experience level does: web/src/experience.ts's
// `describePreset`. This script reads it and rewrites the three places that
// describe it, so they cannot disagree:
//
//   ext/ramify/package.json   the `enumDescriptions` of `ramify.experience`
//   ext/ramify/extension.js   the quick pick's `detail` lines (between the
//                             `gen-experience:start/end` marker comments)
//   INSTALL.md                the table between the `gen-experience` markers
//
//     node scripts/gen-experience.mjs            rewrite them
//     node scripts/gen-experience.mjs --check    exit 1 if any is out of date
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { ensureLib } from "../web/probe/bundle.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");

// The probe bundle (web/probe/lib.mjs) carries experience.ts's describePreset:
// one function writes every level's rows, here and wherever else they appear.
const { describePreset, EXPERIENCES } = await import(pathToFileURL(await ensureLib()).href);

/** One level's rows as one line. */
const line = (level) => describePreset(level).map(([k, v]) => `${k}: ${v}`).join(" · ");

const files = {
  pkg: join(root, "ext/ramify/package.json"),
  ext: join(root, "ext/ramify/extension.js"),
  doc: join(root, "INSTALL.md"),
};
const text = Object.fromEntries(Object.entries(files).map(([k, f]) => [k, readFileSync(f, "utf8")]));
const next = { ...text };

// 1. package.json — the enumDescriptions array right after "ramify.experience".
{
  const at = text.pkg.indexOf('"ramify.experience"');
  const re = /"enumDescriptions": \[[^\]]*\]/;
  const m = re.exec(text.pkg.slice(at));
  if (at < 0 || !m) throw new Error("package.json: ramify.experience enumDescriptions not found");
  const body = EXPERIENCES.map((e) => `            ${JSON.stringify(line(e))}`).join(",\n");
  const repl = `"enumDescriptions": [\n${body}\n          ]`;
  next.pkg = text.pkg.slice(0, at + m.index) + repl + text.pkg.slice(at + m.index + m[0].length);
}

// 2. extension.js — between the marker comments.
{
  const S = "// gen-experience:start";
  const E = "// gen-experience:end";
  const a = text.ext.indexOf(S);
  const b = text.ext.indexOf(E);
  if (a < 0 || b < a) throw new Error("extension.js: gen-experience markers not found");
  const body = EXPERIENCES.map((e) => `  ${e}: ${JSON.stringify(line(e))},`).join("\n");
  next.ext =
    text.ext.slice(0, a) +
    `${S} (scripts/gen-experience.mjs — do not edit by hand)\nconst EXPERIENCE_DETAIL = {\n${body}\n};\n` +
    text.ext.slice(b);
}

// 3. INSTALL.md — a table, levels across.
{
  const S = "<!-- gen-experience:start -->";
  const E = "<!-- gen-experience:end -->";
  const a = text.doc.indexOf(S);
  const b = text.doc.indexOf(E);
  if (a < 0 || b < a) throw new Error("INSTALL.md: gen-experience markers not found");
  const cols = EXPERIENCES.map((e) => describePreset(e));
  const table = [
    `| | ${EXPERIENCES.join(" | ")} |`,
    `| --- | ${EXPERIENCES.map(() => "---").join(" | ")} |`,
    ...cols[0].map(([k], i) => `| ${k} | ${cols.map((c) => c[i][1]).join(" | ")} |`),
  ].join("\n");
  next.doc =
    text.doc.slice(0, a) +
    `${S}\n<!-- generated by scripts/gen-experience.mjs from web/src/experience.ts — do not edit by hand -->\n\n${table}\n\n` +
    text.doc.slice(b);
}

const stale = Object.keys(files).filter((k) => next[k] !== text[k]);
if (check) {
  if (stale.length) {
    console.error(`out of date: ${stale.map((k) => files[k].replace(root + "/", "")).join(", ")}\nrun: node scripts/gen-experience.mjs`);
    process.exit(1);
  }
  console.log("ok: experience descriptions match web/src/experience.ts");
} else {
  for (const k of stale) writeFileSync(files[k], next[k]);
  console.log(stale.length ? `rewrote ${stale.map((k) => files[k].replace(root + "/", "")).join(", ")}` : "already current");
}
